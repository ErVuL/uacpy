"""The harmonisation gates: one rule each over the public API read as one
surface (``uacpy.__all__`` and the ``__all__`` of every submodule ``uacpy``
exposes), or over the package source by AST.

Each gate measures its offenders and compares them with an explicit list of
the known ones still open. The list may only shrink: a new offender fails the
gate, and so does a listed one that is gone (delete its entry).
"""
import ast
import importlib
import inspect
import json
import re
import warnings
from pathlib import Path

import uacpy
from uacpy.core import constants

_PACKAGE = Path(uacpy.__file__).resolve().parent

#: The known offenders of the ratchet gates, by gate (one list per key; the
#: lists only shrink). Regenerated by nothing: an entry is deleted by hand
#: when its offence is fixed, and the gate refuses a new one.
_RATCHET = {key: frozenset(values) for key, values in json.loads(
    (Path(__file__).parent / 'data' / 'harmonisation_ratchets.json')
    .read_text(encoding='utf-8')).items()}


# ── the public surface ────────────────────────────────────────────────────

def _public_objects():
    """``(label, object)`` for every public name: the root's ``__all__``, the
    ``__all__`` of each lazily exposed submodule, ``uacpy.core`` and
    ``uacpy.core.results``, each object once."""
    modules = ['uacpy', *uacpy._LAZY_SUBMODULES.values(), 'uacpy.core',
               'uacpy.core.results']
    seen, out = set(), []
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        for name in modules:
            mod = importlib.import_module(name)
            for attr in getattr(mod, '__all__', ()):
                obj = getattr(mod, attr, None)
                if obj is None or inspect.ismodule(obj) or id(obj) in seen:
                    continue
                seen.add(id(obj))
                out.append((f'{name}.{attr}', obj))
    return out


def _signature(obj):
    try:
        return inspect.signature(obj)
    except (TypeError, ValueError):
        return None


def _public_callables():
    """``(label, callable)`` for every public function, public class (its
    constructor) and public method a public class defines."""
    out = []
    for label, obj in _public_objects():
        if inspect.isclass(obj):
            if issubclass(obj, BaseException):
                continue
            out.append((label, obj))
            for name, member in vars(obj).items():
                if name.startswith('_'):
                    continue
                if isinstance(member, (staticmethod, classmethod)):
                    member = member.__func__
                if inspect.isfunction(member):
                    out.append((f'{label}.{name}', member))
        elif callable(obj):
            out.append((label, obj))
    return out


def _parameters():
    """``(label, Parameter)`` for every parameter of every public callable,
    ``self``/``cls`` and ``*args``/``**kwargs`` left out."""
    for label, obj in _public_callables():
        sig = _signature(obj)
        if sig is None:
            continue
        for p in sig.parameters.values():
            if p.name in ('self', 'cls') or p.kind in (p.VAR_POSITIONAL,
                                                       p.VAR_KEYWORD):
                continue
            yield label, p


def _package_trees():
    """``(relative path, ast tree)`` of every package module (tests,
    examples and third_party left out)."""
    for path in sorted(_PACKAGE.rglob('*.py')):
        rel = path.relative_to(_PACKAGE).as_posix()
        if rel.split('/')[0] in ('tests', 'examples', 'third_party'):
            continue
        yield rel, ast.parse(path.read_text(encoding='utf-8'))


def _check(measured, known, what):
    new = sorted(set(measured) - set(known))
    gone = sorted(set(known) - set(measured))
    problems = [f'new {what}: {x}' for x in new] + \
        [f'{what} gone, delete its entry: {x}' for x in gone]
    assert not problems, '\n'.join(problems)


# ── rule 1: one word per idea ─────────────────────────────────────────────

def _type_of(p):
    """The annotation of ``p`` as text, ``Optional[...]`` and ``None``
    unions reduced to the inner type; ``None`` when it has none."""
    ann = p.annotation
    if ann is p.empty:
        return None
    text = ann if isinstance(ann, str) else \
        ann.__name__ if isinstance(ann, type) else str(ann)
    text = text.replace('typing.', '')
    if text == 'Any':
        return None
    text = re.sub(r'^Optional\[(.*)\]$', r'\1', text)
    text = re.sub(r'\s*\|\s*None$', '', text)
    return text


#: Words that name a carrier wherever they name a parameter.
_CARRIER_WORDS = {'env': 'Environment', 'environment': 'Environment',
                  'receiver': 'Receiver'}


def _carrier_words_naming_something_else():
    return {f'{label}({p.name}: {_type_of(p)})' for label, p in _parameters()
            if p.name in _CARRIER_WORDS and _type_of(p) is not None
            and _CARRIER_WORDS[p.name] not in _type_of(p)}


def test_a_carrier_word_names_its_carrier():
    """``env``, ``environment`` and ``receiver`` name their carrier in every
    public signature that annotates them. H2's known case: ``environment``
    was a Hamilton & Bachman fit string in the grain-size chain (now
    ``hamilton_fit``)."""
    offenders = sorted(_carrier_words_naming_something_else())
    assert not offenders, offenders


#: Names that read ``max_<thing>`` / ``min_<thing>`` because they are caps
#: (at most so many points, so far, so many days), not the largest value of
#: a quantity.
_CAPS = frozenset({'max_points', 'max_order', 'max_distance_km', 'max_days',
                   'min_gap', 'max_depths', 'max_deg', 'min_deg',
                   'max_miss', 'max_launches'})


def _prefix_bounds():
    out = set()
    for label, obj in _public_callables():
        name = label.rsplit('.', 1)[-1]
        if re.match(r'^(max|min)_', name) and name not in _CAPS:
            out.add(label)
        sig = _signature(obj)
        for p in (sig.parameters.values() if sig else ()):
            if re.match(r'^(max|min)_', p.name) and p.name not in _CAPS:
                out.add(f'{label}({p.name})')
    for label, obj in _public_objects():
        if inspect.isclass(obj):
            for name, member in vars(obj).items():
                if isinstance(member, property) and \
                        re.match(r'^(max|min)_', name) and name not in _CAPS:
                    out.add(f'{label}.{name}')
    return out


#: Prefix bounds still open.
_PREFIX_BOUNDS = _RATCHET.get('prefix_bounds', frozenset())


def test_a_bound_is_spelt_quantity_then_bound():
    """The largest value of a quantity, or an interval's upper end, is
    ``<quantity>_max`` (``range_max``, ``depth_max``, ``freq_max``); the
    prefix form is kept for caps only (:data:`_CAPS`). H4's known case:
    ``Environment.max_range`` beside ``Receiver.range_max``."""
    _check(_prefix_bounds(), _PREFIX_BOUNDS, 'prefix bound')


#: Pairs of keywords that name one argument.
_SYNONYM_PAIRS = (('ax', 'axes'), ('angle', 'theta'))


def _synonym_keywords():
    out = set()
    for label, obj in _public_callables():
        sig = _signature(obj)
        names = set(sig.parameters) if sig else set()
        for a, b in _SYNONYM_PAIRS:
            if a in names and b in names:
                out.add(f'{label}({a}, {b})')
    return out


